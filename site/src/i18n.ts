/**
 * Textes du site — bilingues, anglais par défaut (§17).
 *
 * Ne contient que les textes **propres au site**. Tout ce que l'app dit déjà
 * (états, confiance, postes de l'addition, libellés du panneau et du portail)
 * vient de `src/ui/i18n` et de `src/ui/format.ts`, réutilisés tels quels : le
 * site parle exactement comme l'app et aucune chaîne n'est dupliquée.
 *
 * `texts` est un dictionnaire plat : les clés sont celles des attributs
 * `data-i18n` de `site/index.html` et celles utilisées par `render.ts`.
 */

