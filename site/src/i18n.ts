const COPIES: Record<DemoLocale, SiteCopy> = { en, fr };

/** Textes du site dans la langue demandée ; l'anglais sert de repli. */
export function copyOf(locale: DemoLocale): SiteCopy {
  return COPIES[locale] ?? en;
}

/** Un texte du site, jamais `undefined` : la clé elle-même sert de repli. */
export function texte(locale: DemoLocale, key: string): string {
  return copyOf(locale).texts[key] ?? key;
}
